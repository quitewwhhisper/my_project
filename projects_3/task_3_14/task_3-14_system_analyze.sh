#!/bin/bash

echo "=== Анализ дискового пространства ==="
echo ""

# Заголовок таблицы
printf "%-20s %-10s\n" "Файловая система" "Использовано %"

# Обрабатываем вывод df -h
df -h | awk 'NR > 1 {
    # Удаляем символ % из пятого поля
    gsub(/%/, "", $5)
    
    # Выводим информацию
    printf "%-20s %-10s%%\n", $1, $5
    
    # Если использование > 90%, выводим предупреждение
    if ($5 > 90) {
        print "⚠  ПРЕДУПРЕЖДЕНИЕ: Файловая система " $1 " заполнена на " $5 "%!"
    }
}'


#!/bin/bash

echo "=== Замена пробелов на табуляцию в sequences.txt ==="
echo ""

# Показываем исходное содержимое
echo "Исходное содержимое:"
echo "---------------------"
cat sequences.txt
echo ""

# Выполняем замену пробела на табуляцию
# Используем \t для обозначения табуляции
echo "Результат замены (без сохранения в файл):"
echo "------------------------------------------"
sed 's/ /\t/' sequences.txt

echo ""
echo "Чтобы сохранить изменения, используйте флаг -i:"
echo "  sed -i '' 's/ /\t/' sequences.txt"


#!/bin/bash

# Функция проверки прав суперпользователя
check_root() {
    # Проверяем, равен ли EUID нулю
    if [ "$EUID" -eq 0 ]; then
        echo "✓ Пользователь имеет права суперпользователя (root)"
        return 0
    else
        echo "⚠ ПРЕДУПРЕЖДЕНИЕ: Скрипт запущен не от root!"
        echo "   Текущий UID: $EUID"
        echo "   Некоторые операции могут потребовать прав администратора."
        echo "   Завершаем работу скрипта."
        return 1
    fi
}

# Основная часть скрипта

echo "=== Проверка прав доступа ==="

# Вызываем функцию проверки
check_root

# Проверяем результат выполнения функции
if [ $? -eq 0 ]; then
    echo ""
    echo "=== Скрипт продолжает работу ==="
    echo "Вы можете выполнять здесь любые операции, требующие root-прав"
    
    # Пример: показать информацию о системе
    echo "Информация о системе:"
    uname -a
    
else
    echo ""
    echo "=== Скрипт завершен с ошибкой ==="
    echo "Для выполнения этого скрипта требуются права root."
    echo "Запустите скрипт с помощью sudo:"
    echo "  sudo ./check_root.sh"
    exit 1
fi

echo ""
echo "Скрипт успешно выполнен."

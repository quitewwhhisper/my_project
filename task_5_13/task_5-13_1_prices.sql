-- Задание 1: Увеличить цену на 10% для товаров дешевле 1000

-- Шаг 1 (проверка): Посмотрим, какие товары подпадают под обновление
SELECT id, product_id, price, 'будет изменено на ' || (price * 1.1) AS новое_значение
FROM prices
WHERE price < 1000;

-- Шаг 2 (обновление): Увеличиваем цену на 10%
UPDATE prices
SET price = price * 1.1
WHERE price < 1000;

-- Шаг 3 (проверка результата): Посмотрим, что изменилось
SELECT id, product_id, price
FROM prices
WHERE price < 1100;  -- теперь цена стала чуть выше 1000